@lru_cache(maxsize=512)
def pixmap(name: str, color: str, size: int = 18, dpr: float = 0.0, stroke: float = 1.75) -> QPixmap:
    dpr = dpr or (QGuiApplication.primaryScreen().devicePixelRatio() if QGuiApplication.primaryScreen() else 1.0)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{_P[name]}</svg>')
    px = int(round(size * dpr))
    pm = QPixmap(px, px)
    pm.setDevicePixelRatio(dpr)
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    QSvgRenderer(QByteArray(svg.encode())).render(p, QRectF(0, 0, size, size))
    p.end()
    return pm


def icon(name: str, normal: str, active: str | None = None, disabled: str | None = None, size: int = 18) -> QIcon:
    ic = QIcon()
    ic.addPixmap(pixmap(name, normal, size), QIcon.Mode.Normal)
    ic.addPixmap(pixmap(name, active or normal, size), QIcon.Mode.Active)
    ic.addPixmap(pixmap(name, disabled or normal, size), QIcon.Mode.Disabled)
    return ic
